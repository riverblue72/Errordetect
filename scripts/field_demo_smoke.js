"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const { chromium } = require("playwright");
const base = process.env.SITE_URL || "http://127.0.0.1:62309/";
const output = process.env.QA_OUTPUT || "/private/tmp/surfacetrace-field-demo-qa";

(async () => {
  await fs.mkdir(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: process.env.CHROME_PATH || "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome" });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, acceptDownloads: true });
  const page = await context.newPage(), errors = [], failedAssets = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("response", response => { if (response.status() >= 400) failedAssets.push(response.url()); });
  const state = () => page.evaluate(() => window.surfaceTraceFieldDemo.getState());
  const status = () => page.evaluate(() => window.surfaceTraceFieldDemo.getStatus());
  const save = async verdict => {
    await page.locator(`[data-verdict="${verdict}"]`).click();
    await page.locator("#saveDecision").click();
  };
  const receive = async scenario => {
    await page.locator("#scenario").selectOption(scenario);
    await page.locator("#receive").click();
    if (await page.locator("#resetDialog").isVisible()) await page.locator("#confirmReset").click();
  };
  const capture = async name => {
    await page.locator("#toast").evaluate(element => { element.hidden = true; });
    await page.evaluate(() => window.scrollTo({ top: 0, behavior: "instant" }));
    await page.screenshot({ path: path.join(output, name + ".png"), fullPage: true });
  };
  try {
    await page.goto(new URL("field-demo.html", base).href);
    await page.waitForFunction(() => !!window.surfaceTraceFieldDemo);
    assert(await page.locator("#emptyState").isVisible());
    await capture("01-incoming");
    await receive("defect");
    assert.equal(await page.locator(".queue-item").count(), 8);
    assert.equal(await page.locator(".queue-item:disabled").count(), 6);
    assert(await page.locator("#saveDecision").isDisabled());
    assert.equal(await page.locator(".truth-column:visible").count(), 0);
    assert.equal((await status()).budget, 2);
    await page.locator("#toggleHeat").click();
    assert(await page.locator("#heatPhoto").isVisible());
    assert.equal(await page.locator("#toggleHeat").getAttribute("aria-pressed"), "true");
    await page.locator("#reviewNote").fill("선 형태 확인 <script>window.injected=true</script>");
    await capture("02-inspection");
    await save("defect");
    assert.equal((await status()).reviewed, 1);
    assert.equal((await state()).active, 1);
    await page.keyboard.press("3");
    assert.equal(await page.locator('[data-verdict="hold"]').getAttribute("aria-pressed"), "true");
    await page.locator("#saveDecision").click();
    assert.equal((await status()).budget, 8);
    assert.equal(await page.locator(".queue-item:disabled").count(), 0);
    for (const verdict of ["defect", "defect", "defect", "defect", "normal", "normal"]) await save(verdict);
    assert.equal((await state()).phase, "summary");
    assert.equal((await status()).reviewed, 8);
    assert.equal(await page.evaluate(() => window.injected), undefined);
    assert.equal(await page.locator("#normalCount").innerText(), "2장");
    assert.equal(await page.locator("#defectCount").innerText(), "5장");
    assert.equal(await page.locator("#holdCount").innerText(), "1장");
    assert.equal(await page.locator("#recordRows tr").count(), 8);
    const firstDownload = page.waitForEvent("download");
    await page.locator("#downloadRecord").click();
    const file = await firstDownload;
    const exported = JSON.parse(await fs.readFile(await file.path(), "utf8"));
    assert.equal(exported.records.length, 8);
    assert.equal(exported.modelWeightsUpdated, false);
    assert.equal(exported.activeReference, "frozen-source");
    assert(!exported.records.some(record => "publishedDatasetLabel" in record));
    assert.match(exported.records[0].userReview.note, /<script>/);
    await page.reload();
    await page.waitForFunction(() => !!window.surfaceTraceFieldDemo);
    assert.equal((await status()).reviewed, 8);
    assert(await page.locator("#summary").isVisible());
    await page.locator("#compareTruth").click();
    assert.match(await page.locator("#truthResult").innerText(), /8장 중 7장 일치/);
    assert.equal(await page.locator("td.truth-column:visible").count(), 8);
    await capture("03-records");
    await page.locator("#openCandidate").click();
    assert.equal(await page.locator("#normalPhotos figure").count(), 2);
    assert(await page.locator("#showValidation").isDisabled());
    await page.locator("#requestValidation").click();
    assert((await state()).candidateRequested);
    await page.locator("#showValidation").click();
    assert.equal(await page.locator("#validationMetrics > div").count(), 3);
    const metrics = await page.locator("#validationMetrics").innerText();
    for (const value of ["1,050", "202", "153", "48", "40"]) assert(metrics.includes(value));
    assert.match(await page.locator(".historical-scope").innerText(), /이번 사진 선택으로 계산한 결과가 아닙니다/);
    await capture("04-reference-review");
    await page.locator("#finishCandidate").click();
    assert((await state()).baselineKept);
    await page.locator("#editReviews").click();
    await save("normal");
    await page.locator("#editReviews").click();
    await page.locator('.queue-item[data-index="1"]').click();
    await save("normal");
    assert.equal((await status()).budget, 8, "Already requested reviews must not silently disappear when pilot decisions are edited");
    assert.equal((await status()).reviewed, 8);
    assert.equal((await state()).candidateRequested, false);

    await receive("normal");
    assert.equal(await page.locator(".queue-item").count(), 2);
    assert(await page.locator("#toggleHeat").isDisabled());
    await save("normal"); await save("normal");
    assert.equal((await status()).budget, 2);
    assert.equal(await page.locator("#unrequestedCount").innerText(), "6장");
    assert.match(await page.locator("#summaryDescription").innerText(), /남은 여섯 장을 정상으로 판정한 것은 아닙니다/);
    await capture("05-two-check-stop");
    await receive("normal");
    await save("hold"); await save("normal");
    assert((await status()).pending);
    assert.equal((await status()).budget, 8);
    assert.equal((await status()).available, 2);
    assert.match(await page.locator("#summaryTitle").innerText(), /추가 검수 사진을 요청/);
    await page.locator("#restart").click();
    await page.locator("#cancelReset").click();
    assert.equal((await status()).reviewed, 2);
    await page.locator("#restart").click();
    await page.locator("#confirmReset").click();
    assert(await page.locator("#emptyState").isVisible());
    assert.equal((await state()).caseId, null);
    await page.setViewportSize({ width: 800, height: 1000 });
    await receive("defect");
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), "Tablet horizontal overflow");
    await capture("tablet-review");
    await page.setViewportSize({ width: 390, height: 844 });
    for (const step of ["empty", "review", "summary"]) {
      if (step === "empty") {
        await page.locator("#restart").click();
        await page.locator("#confirmReset").click();
      }
      if (step === "review") await receive("defect");
      if (step === "summary") { await save("normal"); await save("normal"); }
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `${step}: mobile horizontal overflow`);
      await capture(`mobile-${step}`);
    }
    assert.deepEqual(errors, []);
    assert.deepEqual(failedAssets, []);
    const restricted = await browser.newContext();
    await restricted.addInitScript(() => { Storage.prototype.setItem = () => { throw new Error("Storage unavailable"); }; });
    const restrictedPage = await restricted.newPage();
    await restrictedPage.goto(new URL("field-demo.html", base).href);
    await restrictedPage.locator("#receive").click();
    assert.match(await restrictedPage.locator("#storageStatus").innerText(), /기록을 내려받아/);
    assert(await restrictedPage.locator("#workbench").isVisible());
    await restricted.close();
    console.log(JSON.stringify({ status: "passed", scenarios: ["expanded-eight", "stop-after-two", "additional-photos-pending"], persistence: true, export: true, referenceReview: true, mobileOverflow: false, screenshots: output }));
  } finally { await context.close(); await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
